"""Safe declarative recipe prototype for the Script Workshop.

ONLY trusted built-in pure string operations are supported. No eval, exec,
shell, filesystem access, imports, plugin execution or network. Recipe inputs
and outputs are capped. This is not a general script sandbox.
"""
from __future__ import annotations

from dataclasses import dataclass
import hashlib
import json
import re


OPS = frozenset({
    "normalize_newlines", "strip_lines", "drop_empty_lines",
    "deduplicate_lines", "lowercase", "sha256"
})
_ALLOWED = frozenset({"recipe_id", "version", "steps", "kind", "scope"})
MAX_TEXT = 200_000
MAX_STEPS = 12


@dataclass(frozen=True)
class Recipe:
    recipe_id: str
    version: str
    steps: tuple[str, ...]
    kind: str
    scope: str

    @classmethod
    def parse(cls, obj: dict) -> "Recipe":
        if not isinstance(obj, dict) or set(obj) != _ALLOWED:
            raise ValueError("Unknown/missing recipe fields")
        for key in ("recipe_id", "version"):
            if not isinstance(obj[key], str) or not re.fullmatch(
                r"[a-zA-Z0-9_.-]{1,80}", obj[key]):
                raise ValueError("Invalid recipe identity")
        if obj["kind"] != "pure_text":
            raise ValueError("Only pure_text recipes are supported")
        if obj["scope"] != "synthetic_or_explicitly_approved_text":
            raise ValueError("Unapproved input scope")
        steps = obj["steps"]
        if (not isinstance(steps, list) or not 1 <= len(steps) <= MAX_STEPS
                or any(type(step) is not str or step not in OPS for step in steps)):
            raise ValueError("Unknown operation or invalid step count")
        return cls(obj["recipe_id"], obj["version"],
                   tuple(steps), obj["kind"], obj["scope"])

    def manifest_bytes(self) -> bytes:
        return json.dumps({
            "recipe_id": self.recipe_id, "version": self.version,
            "steps": list(self.steps), "kind": self.kind,
            "scope": self.scope
        }, sort_keys=True, separators=(",", ":")).encode("utf-8")


def apply(recipe: Recipe, text: str) -> str:
    """Run only whitelisted pure operations on authorized caller-supplied text."""
    if not isinstance(text, str) or len(text) > MAX_TEXT:
        raise ValueError("Input too large or not text")
    value = text
    for step in recipe.steps:
        if step == "normalize_newlines":
            value = value.replace("\r\n", "\n").replace("\r", "\n")
        elif step == "strip_lines":
            value = "\n".join(line.strip() for line in value.split("\n"))
        elif step == "drop_empty_lines":
            value = "\n".join(line for line in value.split("\n") if line)
        elif step == "deduplicate_lines":
            value = "\n".join(dict.fromkeys(value.split("\n")))
        elif step == "lowercase":
            value = value.lower()
        elif step == "sha256":
            value = hashlib.sha256(value.encode("utf-8")).hexdigest()
        else:
            raise ValueError("Unsupported operation")
        if len(value) > MAX_TEXT:
            raise ValueError("Output exceeds maximum size")
    return value


def evaluate_fixtures(recipe: Recipe, fixtures: list[dict]) -> dict:
    """Independent string-output fixtures; do not trust agent-generated answers.

    The caller must ensure fixtures and expected outputs were reviewed by a
    human or separate test oracle, and not generated by the same candidate.
    """
    if not isinstance(fixtures, list) or not 1 <= len(fixtures) <= 50:
        raise ValueError("Fixture count must be 1..50")
    outcomes = []
    for i, case in enumerate(fixtures):
        if not isinstance(case, dict) or set(case) != {"input", "expected"}:
            raise ValueError("Invalid fixture")
        if not isinstance(case["expected"], str):
            raise ValueError("Expected output must be a string")
        actual = apply(recipe, case["input"])
        outcomes.append({"fixture": i, "passed": actual == case["expected"]})
    return {
        "recipe_id": recipe.recipe_id,
        "recipe_sha256": hashlib.sha256(recipe.manifest_bytes()).hexdigest(),
        "fixture_total": len(outcomes),
        "fixture_passed": sum(x["passed"] for x in outcomes),
        "all_passed": all(x["passed"] for x in outcomes),
        "tests": outcomes,
        "status": "local_pure_function_test_not_independent_approval",
    }
